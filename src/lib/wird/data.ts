export type WirdSessionKey = "morning" | "evening";

export interface WirdItem {
  /** ترتيب الذكر داخل الوِرد (١..٢٨) */
  order: number;
  /** اسم الذكر (يُعرض فوق النص) */
  name: string;
  /** نص الذكر كاملًا — بدون رقم التكرار وبدون مصدر */
  text: string;
  /** عدد التكرار المطلوب */
  repeat: number;
}

export interface WirdSession {
  key: WirdSessionKey;
  title: string;
  description: string;
  items: WirdItem[];
}

